import { useCallback, useEffect, useState } from 'react';
import Card from '../components/ui/Card';
import StatCard from '../components/ui/StatCard';
import ConfirmDialog from '../components/ui/ConfirmDialog';
import { Badge } from '../components/ui/Badge';
import { EmptyState, LoadingState } from '../components/ui/States';
import SessionPicker from '../components/SessionPicker';
import { useActiveSession } from '../hooks/useActiveSession';
import { simulationApi } from '../services/endpoints';
import { formatTime } from '../utils/format';

const PROFILES = [
  { id: 'benign', label: 'Benign', desc: 'Low-risk baseline telemetry' },
  { id: 'balanced', label: 'Balanced', desc: 'Mixed indicators' },
  { id: 'aggressive', label: 'Aggressive', desc: 'Strong keylogger-like signals' },
];

export default function ThreatSimulationPage() {
  const { sessions, activeId, selectSession, startSession, loading } = useActiveSession();
  const [profile, setProfile] = useState('balanced');
  const [running, setRunning] = useState(false);
  const [events, setEvents] = useState([]);
  const [busy, setBusy] = useState(false);
  const [confirmReset, setConfirmReset] = useState(false);

  const loadEvents = useCallback(async () => {
    if (!activeId) {
      setEvents([]);
      return;
    }
    try {
      setEvents(await simulationApi.events(activeId));
    } catch {
      setEvents([]);
    }
  }, [activeId]);

  useEffect(() => {
    loadEvents();
  }, [loadEvents]);

  async function ensureSession() {
    if (activeId) return activeId;
    const s = await startSession('Threat simulation');
    return s.id;
  }

  async function onStart() {
    setBusy(true);
    try {
      const sid = await ensureSession();
      await simulationApi.start(sid, profile);
      setRunning(true);
      await loadEvents();
    } finally {
      setBusy(false);
    }
  }

  async function onGenerate(count) {
    setBusy(true);
    try {
      const sid = await ensureSession();
      await simulationApi.generate(sid, count, profile);
      await loadEvents();
    } finally {
      setBusy(false);
    }
  }

  async function onStop() {
    if (!activeId) return;
    setBusy(true);
    try {
      await simulationApi.stop(activeId);
      setRunning(false);
    } finally {
      setBusy(false);
    }
  }

  async function onReset() {
    setConfirmReset(false);
    if (!activeId) return;
    setBusy(true);
    try {
      await simulationApi.reset(activeId);
      setRunning(false);
      await loadEvents();
    } finally {
      setBusy(false);
    }
  }

  const totalKb = events.reduce((a, e) => a + e.keyboard_events, 0);
  const withPersistence = events.filter((e) => e.persistence_indicator).length;
  const withNetwork = events.filter((e) => e.network_activity).length;

  if (loading) return <LoadingState />;

  return (
    <div className="space-y-5">
      <div>
        <h1 className="text-xl font-bold text-slate-100">Synthetic Threat Simulation</h1>
        <p className="text-sm text-slate-400">
          Generate <span className="text-accent">fabricated</span> telemetry for a
          hypothetical keylogging process. Nothing here touches the real system.
        </p>
      </div>

      <div className="rounded-xl border border-accent/30 bg-accent/5 p-3 text-xs text-slate-300">
        ⓘ All values below are randomly generated by the simulator to exercise the
        detection engine. No real processes, files, or network connections are involved.
      </div>

      <SessionPicker
        sessions={sessions}
        activeId={activeId}
        onSelect={selectSession}
        onStart={() => startSession('Threat simulation')}
        busy={busy}
      />

      <Card title="Simulation controls" subtitle="Pick a profile and drive the synthetic engine">
        <div className="grid grid-cols-1 gap-3 sm:grid-cols-3 mb-4">
          {PROFILES.map((p) => (
            <button
              key={p.id}
              onClick={() => setProfile(p.id)}
              className={`rounded-lg border p-3 text-left transition-colors ${
                profile === p.id
                  ? 'border-accent bg-accent/10'
                  : 'border-base-700 hover:bg-base-800'
              }`}
            >
              <p className="text-sm font-medium text-slate-100">{p.label}</p>
              <p className="text-xs text-slate-400">{p.desc}</p>
            </button>
          ))}
        </div>
        <div className="flex flex-wrap items-center gap-2">
          <button className="btn-primary" onClick={onStart} disabled={busy}>
            ▶ Start simulation
          </button>
          <button className="btn-ghost" onClick={() => onGenerate(1)} disabled={busy}>
            + Generate event
          </button>
          <button className="btn-ghost" onClick={() => onGenerate(10)} disabled={busy}>
            + Generate 10
          </button>
          <button className="btn-ghost" onClick={onStop} disabled={busy || !running}>
            ■ Stop
          </button>
          <button
            className="btn-danger"
            onClick={() => setConfirmReset(true)}
            disabled={busy || !events.length}
          >
            Reset
          </button>
          <Badge tone={running ? 'success' : 'neutral'}>
            {running ? 'RUNNING' : 'IDLE'}
          </Badge>
        </div>
      </Card>

      <div className="grid grid-cols-2 gap-4 lg:grid-cols-4">
        <StatCard label="Synthetic events" value={events.length} icon="🧪" accent="text-slate-100" />
        <StatCard label="Total keyboard events" value={totalKb} icon="⌨️" />
        <StatCard label="With persistence" value={withPersistence} icon="📌" accent="text-risk-high" />
        <StatCard label="With network" value={withNetwork} icon="🌐" accent="text-risk-critical" />
      </div>

      <Card title="Generated telemetry" subtitle="Most recent synthetic events">
        {!events.length ? (
          <EmptyState
            title="No telemetry yet"
            hint="Start the simulation or generate events to populate the detection engine."
          />
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full text-sm">
              <thead>
                <tr className="text-left text-xs uppercase tracking-wide text-slate-500 border-b border-base-700">
                  <th className="py-2 pr-3">Time</th>
                  <th className="py-2 pr-3">Process</th>
                  <th className="py-2 pr-3">KB events</th>
                  <th className="py-2 pr-3">Rate/min</th>
                  <th className="py-2 pr-3">Persist</th>
                  <th className="py-2 pr-3">Network</th>
                  <th className="py-2 pr-3">Indicators</th>
                </tr>
              </thead>
              <tbody>
                {[...events].reverse().map((e) => (
                  <tr key={e.id} className="border-b border-base-800/60">
                    <td className="py-2 pr-3 text-slate-400">{formatTime(e.created_at)}</td>
                    <td className="py-2 pr-3 font-mono text-slate-200">{e.process_name}</td>
                    <td className="py-2 pr-3">{e.keyboard_events}</td>
                    <td className="py-2 pr-3">{e.event_rate_per_min}</td>
                    <td className="py-2 pr-3">{e.persistence_indicator ? '✅' : '—'}</td>
                    <td className="py-2 pr-3">{e.network_activity ? '✅' : '—'}</td>
                    <td className="py-2 pr-3">
                      <div className="flex flex-wrap gap-1">
                        {e.risk_indicators.map((r) => (
                          <span key={r} className="badge bg-base-800 text-slate-300 border border-base-600">
                            {r}
                          </span>
                        ))}
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Card>

      <ConfirmDialog
        open={confirmReset}
        danger
        title="Reset simulation?"
        message="This permanently deletes all synthetic telemetry for this session."
        confirmLabel="Reset"
        onConfirm={onReset}
        onCancel={() => setConfirmReset(false)}
      />
    </div>
  );
}

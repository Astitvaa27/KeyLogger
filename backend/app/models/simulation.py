"""Synthetic simulation event model.

These rows contain FABRICATED telemetry only. Nothing here is read from the
real operating system, real processes, or real network activity. The values
are generated by the simulation service to exercise the detection engine in a
safe, self-contained way.
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import TYPE_CHECKING

from sqlalchemy import (
    Boolean,
    DateTime,
    ForeignKey,
    Integer,
    JSON,
    String,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base

if TYPE_CHECKING:
    from app.models.session import Session


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


class SimulationEvent(Base):
    __tablename__ = "simulation_events"

    id: Mapped[int] = mapped_column(primary_key=True)
    session_id: Mapped[int] = mapped_column(
        ForeignKey("sessions.id", ondelete="CASCADE"), index=True, nullable=False
    )
    # Fabricated, human-readable name for the hypothetical process.
    process_name: Mapped[str] = mapped_column(String(128), nullable=False)
    keyboard_events: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    persistence_indicator: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    network_activity: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    # Synthetic events-per-minute rate for the hypothetical process.
    event_rate_per_min: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    # List[str] of risk indicator keys, e.g. ["persistence_indicator", ...].
    risk_indicators: Mapped[list] = mapped_column(JSON, default=list, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=_utcnow, nullable=False
    )

    session: Mapped["Session"] = relationship(back_populates="simulation_events")

    def __repr__(self) -> str:  # pragma: no cover
        return f"<SimulationEvent process={self.process_name!r} kb={self.keyboard_events}>"
